from astrbot.api.event import AstrMessageEvent

from .base import PluginService


class HelpService(PluginService):
    """Help service."""

    async def help_command(self, event: AstrMessageEvent):
        """显示帮助信息"""
        user_id = event.get_sender_id()
        user_config = self.get_user_config(user_id)
        global_cfg = self.get_global_config()
        is_user_auth_mode = global_cfg.get("require_user_auth", True)

        help_text = f"""📚 OpenList 助手帮助
💡 所有指令以「素材」开头，使用全中文命令。

---
核心导航指令
---
▶️ `素材 列表 [路径|序号]`
   - 浏览目录: 列出内容，若文件过多会自动分页。
     - 示例: `素材 列表`
     - 示例: `素材 列表 /movies`
   - 进入子目录:
     - 示例: `素材 列表 1` (如果1是目录)
   - 获取链接: 获取文件的下载链接，并以 txt 附件发送。
     - 示例: `素材 列表 2` (如果2是文件)

▶️ `素材 下一页` - 下一页
▶️ `素材 上一页` - 上一页

▶️ `素材 上一级`
   - 返回到上级目录。

---
文件操作指令
---
📥 `素材 下载 <路径|序号>`
   - 直接下载: 将文件作为附件发送给您。
     - 示例: `素材 下载 3` (下载列表中的3号文件)
     - 示例: `素材 下载 /docs/report.pdf`

🔍 `素材 搜索 <关键词> [路径]`
   - 搜索文件。注意：搜索依赖服务器索引，可能不是最新的。
     - 示例: `素材 搜索 年度报告`

ℹ️ `素材 信息 <路径>`
   - 查看文件或目录的详细信息，不支持序号。
     - 示例: `素材 信息 /docs/report.pdf`

👁️ `素材 预览 <路径|序号>`
   - 预览内容: 支持文本文件内容预览或压缩包目录查看。
     - 示例: `素材 预览 1`
     - 示例: `素材 预览 /data/config.txt`

📂 `素材 新建 <名称|路径>`
   - 新建文件夹: 在当前目录或指定路径创建。
     - 示例: `素材 新建 new_folder`

🗑️ `素材 删除 <路径|序号>`
   - 删除项目: 删除文件或文件夹（谨慎操作）。
     - 示例: `素材 删除 4`
     - 示例: `素材 删除 /tmp/stale_file.txt`

📤 `素材 上传 [说明]` (投稿模式)
   - 先发送图片、视频或文件，再在 5 分钟内发送本指令上传到你的个人投稿文件夹。
   - `素材 上传 说明文字`: 上传到个人文件夹，文件自动重命名为 `{{时间戳}}_{{说明}}.{{原扩展名}}`，如 `202608291400_我的生日.jpg`。
   - 投稿模式下只能访问自己的投稿文件夹，无法查看其他用户或退出到上级目录；搜索/删除/新建目录不可用。
   - 上传后自动生成个人文件夹 `<投稿根路径>/<你的QQ号>`。

---
插件配置指令
---
⚙️ `素材 配置 向导` - 推荐新用户使用，启动交互式配置向导。
⚙️ `素材 配置 查看` - 显示您当前的配置。
⚙️ `素材 配置 设置 <键> <值>` - 修改配置项。
   - 示例: `素材 配置 设置 openlist_url http://127.0.0.1:5244`
   - 示例: `素材 配置 设置 max_upload_size 100`
⚙️ `素材 配置 测试` - 测试与服务器的连接。
⚙️ `素材 配置 清缓存` - 清除文件列表缓存。
"""

        if is_user_auth_mode:
            help_text += f"""

👤 当前模式: 用户独立认证
   - 每位用户都需要使用 `素材 配置 向导` 单独配置自己的 Openlist 账户信息。"""

            if not self._validate_config(user_config):
                help_text += f"""

⚠️ 操作提示
   您尚未完成配置，请发送 `素材 配置 向导` 开始配置向导。"""
        else:
            help_text += f"""

🌐 当前模式: 全局共享
   - 所有用户共享管理员预设的 Openlist 服务器连接，无需单独配置。"""

        help_text += f"""

💡 通用提示:
1.  路径区分大小写，以 `/` 开头表示根目录。
2.  `列表` 获取链接，`下载` 直接发送文件。
3.  管理员可在机器人后台的插件配置页面调整全局设置。"""

        yield event.plain_result(help_text)
